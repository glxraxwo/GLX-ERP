/**
 * Dynamic Condition Translator
 * Automatically translates standard and semi-custom conditions between EN, SI, and TA.
 */
export const translateCondition = (type, rawText, targetLang = 'en') => {
    if (!rawText || typeof rawText !== 'string') {
        return defaultConditions[type]?.[targetLang] || defaultConditions[type]?.en || '';
    }

    if (targetLang === 'en') {
        return rawText;
    }

    const trimmed = rawText.trim();

    // 1. Condition of Payments
    if (type === 'conditionOfPayments') {
        const advMatch = trimmed.match(/(\d+)\s*%/);
        const advPerc = advMatch ? advMatch[1] : '0';

        if (targetLang === 'si') {
            return `a). ස්ථිර ඇණවුම සමඟ ${advPerc}% අත්තිකාරම් ගෙවීම.\nb). වැඩ නිම වූ පසු ඉතිරි ගෙවීම සිදු කළ යුතුය.`;
        }
        if (targetLang === 'ta') {
            return `a). உறுதியான ஆர்டருடன் ${advPerc}% முன்பணம்.\nb). வேலை முடிந்தவுடன் மீதி தொகை செலுத்தப்பட வேண்டும்.`;
        }
    }

    // 2. Completion of Work
    if (type === 'completionOfWork') {
        const daysMatch = trimmed.match(/(\d+)\s*(?:to|-)\s*(\d+)/i);
        if (daysMatch) {
            const [, fromD, toD] = daysMatch;
            if (targetLang === 'si') {
                return `ඇණවුම තහවුරු කිරීමෙන් පසු වැඩ කරන දින ${fromD} සිට ${toD} දක්වා.`;
            }
            if (targetLang === 'ta') {
                return `ஆர்டர் உறுதிப்படுத்தப்பட்ட பிறகு ${fromD} முதல் ${toD} வேலை நாட்கள்.`;
            }
        }
        const singleDayMatch = trimmed.match(/(\d+)\s*working\s*days/i);
        if (singleDayMatch) {
            const d = singleDayMatch[1];
            if (targetLang === 'si') return `ඇණවුම තහවුරු කිරීමෙන් පසු වැඩ කරන දින ${d}ක් ඇතුළත.`;
            if (targetLang === 'ta') return `ஆர்டர் உறுதிப்படுத்தப்பட்ட பிறகு ${d} வேலை நாட்களுக்குள்.`;
        }
        return defaultConditions.completionOfWork[targetLang] || defaultConditions.completionOfWork.en;
    }

    // 3. Validity
    if (type === 'validityQuotation') {
        const valMatch = trimmed.match(/(\d+)\s*working\s*days/i) || trimmed.match(/(\d+)\s*days/i);
        const days = valMatch ? valMatch[1] : '30';
        if (targetLang === 'si') {
            return `නිකුත් කළ දින සිට වැඩ කරන දින ${days}ක් පමණි..`;
        }
        if (targetLang === 'ta') {
            return `வழங்கப்பட்ட தேதியிலிருந்து ${days} வேலை நாட்கள்..`;
        }
        return defaultConditions.validityQuotation[targetLang] || defaultConditions.validityQuotation.en;
    }

    // 4. Warranty
    if (type === 'warrantyCondition') {
        if (targetLang === 'si') {
            return defaultConditions.warrantyCondition.si;
        }
        if (targetLang === 'ta') {
            return defaultConditions.warrantyCondition.ta;
        }
    }

    return rawText;
};

export const getDocTranslation = (lang = 'en') => {
    return docTranslations[lang] || docTranslations.en;
};

